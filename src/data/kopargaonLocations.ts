/**
 * Reverse geocode GPS coordinates to extract readable town / taluka / district
 */
export async function getReverseGeocodedLocation(lat: number, lon: number): Promise<string> {
  try {
    const res = await fetch(
      `https://nominatim.openstreetmap.org/reverse?format=json&lat=${lat}&lon=${lon}&zoom=14&addressdetails=1`,
      {
        headers: {
          'Accept-Language': 'mr,en'
        }
      }
    );

    if (res.ok) {
      const data = await res.json();
      const addr = data.address || {};

      const village = addr.village || addr.suburb || addr.town || addr.hamlet || addr.neighbourhood || '';
      const taluka = addr.county || addr.subdistrict || addr.district || '';
      const stateDistrict = addr.state_district || addr.city || '';

      const parts = [village, taluka, stateDistrict].filter(Boolean);
      if (parts.length > 0) {
        return parts.join(', ');
      }
    }
  } catch (err) {
    console.warn('Reverse geocoding error:', err);
  }

  // Fallback to formatted GPS coordinates
  return `GPS (${lat.toFixed(4)}, ${lon.toFixed(4)}) - कोपरगाव परिसर`;
}
